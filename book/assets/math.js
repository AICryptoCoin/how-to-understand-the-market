/* =============================================================
   Настройка рендерера формул. Читается MathJax при запуске,
   поэтому подключается СТРОГО ДО vendor/mathjax/tex-svg.js.

   Почему сборка tex-svg: она рисует формулы путями SVG и не просит
   ни одного файла шрифта. Книга лежит зеркалом на GitHub Pages и
   должна открываться с диска, без сети; вариант с шрифтами добавил
   бы шесть десятков файлов и класс поломки, который приборы приёмки
   не видят, — отсутствующий шрифт выглядит как пустое место.

   Происхождение, версия и хеш — vendor/mathjax/README.md.
   ============================================================= */

window.MathJax = {
  tex: {
    /* Разделители ТОЛЬКО скобочные. Доллар разделителем не является и
       являться не должен: книга про рынки, и «$100» в прозе открыло бы
       математику до следующего доллара. Глава 9 писалась долларами и
       переведена на скобки 2026-09-23; запрет стережёт детектор
       math_dollar в tools/mathcheck.py. */
    inlineMath: [["\\(", "\\)"]],
    displayMath: [["\\[", "\\]"]],
    processEscapes: false,
    processEnvironments: true,
    /* Формулы в книге не нумеруются: нумерация у рисунков и таблиц. */
    tags: "none"
  },

  svg: {
    /* Глифы объявляются один раз на страницу и переиспользуются ссылкой.
       На главе с 249 формулами это разница в вес документа, а не мелочь. */
    fontCache: "global",
    displayAlign: "center",
    displayIndent: "0"
  },

  options: {
    /* Меню выключено намеренно. Из него включается речевой движок, который
       MathJax тянет с cdn.jsdelivr.net, — единственный сетевой путь во всей
       сборке. Выключенное меню закрывает его совсем, и книга остаётся
       работоспособной без сети. Заодно правая кнопка над формулой снова
       принадлежит читателю. */
    enableMenu: false,

    /* Список по умолчанию плюс svg: подписи внутри рисунков — это чернила
       фигуры, их размечает STYLE-GUIDE §7, и рендереру там делать нечего.
       Сегодня разделителей в <svg> ноль (проверено счётом), правило стоит
       на будущее. */
    skipHtmlTags: [
      "script", "noscript", "style", "textarea", "pre", "code",
      "annotation", "annotation-xml", "svg"
    ],
    ignoreHtmlClass: "no-math"
  },

  startup: {
    typeset: true
  }
};
